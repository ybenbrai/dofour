let nextId = 1;

function makeFighter(spec: FighterSpec): Fighter {
  const pos = tilePos(spec.x, spec.y);
  return {
    id: `f${nextId++}`,
    name: spec.name,
    kind: spec.kind,
    shape: spec.shape,
    team: spec.team,
    x: spec.x,
    y: spec.y,
    vx: pos.x,
    vy: pos.y,
    hp: spec.hp,
    maxHp: spec.hp,
    ap: spec.ap,
    maxAp: spec.ap,
    mp: spec.mp,
    maxMp: spec.mp,
    initiative: spec.initiative,
    shield: 0,
    statuses: [],
    alive: true,
    spells: spec.spells,
    color: spec.color,
    accent: spec.accent,
    skin: spec.skin,
    flash: 0,
    bobSeed: Math.random() * Math.PI * 2,
  };
}

